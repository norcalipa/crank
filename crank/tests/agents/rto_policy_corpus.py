"""Office-policy reading corpus (issue #537).

Each row is ``(text, today, proposed, category, source)``:

* ``today`` is what ``matching._rto_days`` returns on the base code, pinned by
  ``test_rto_policy_corpus.py``. It is the record and never edited.
* ``proposed`` is the reading the owner reviews. Stage 1 changes no behaviour;
  stage 2 makes ``_rto_days`` return this column, and the owner edits the
  column, not the rules.

Both are ``0..5`` in-office days, or ``None`` for unknown. The rules that
produce ``proposed`` (frozen in ``rto_reading_report.proposed_rto_days``):

1. Exact codes and labels as today, plus ``on-site`` and ``on site``.
2. Mixed or conditional wording ("remote or hybrid", "flexible", "depends on the
   team") is unknown.
3. Negated or optional office ("no office required", "office optional") with no
   in-office day count is remote (0).
4. Occasional attendance (offsites, onboarding, quarterly) is unknown.
5. An explicit day count next to an office / on-site / in-person / RTO / hybrid
   word is that count (1-5); a range ("2-3 days") or a count of remote days is
   unknown; "Monday-Friday", "full-time in office" are 5. Hybrid on named
   weekdays is unknown.
6. Office-first / return-to-office / in-office wording, with or without remote
   exceptions, is 5.
7. Negated remote ("not remote", "no remote", "remote not permitted") says
   nothing about hybrid or in-office: unknown. A negated hybrid is unknown
   unless the text goes on to say remote.
8. Hybrid without a count keeps today's 3 (flagged for the owner: unknown is the
   alternative).
9. Remote wording, including an incidental office mention (hubs, coworking, "an
   office in X"), is 0.
10. Anything else is unknown.
"""

